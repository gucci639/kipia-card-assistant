def build_user_prompt(product: ProductInput, pre_missing_fields: list[str]) -> str:
    """Формирует пользовательский промпт с входными данными и подсказкой по пустым полям."""
    payload = {
        "name": product.name or "данных нет",
        "manufacturer": product.manufacturer or "данных нет",
        "specs": product.specs if product.specs else {"характеристики": "данных нет"},
        "description": product.description or "данных нет",
    }
    missing_hint = (
        "\nОбрати внимание: предварительный анализатор обнаружил нехватку следующих данных: "
        + ", ".join(pre_missing_fields)
        + ". Обязательно отрази их как 'данных нет' в характеристиках и в списке уточнений, НЕ выдумывай их значения!"
        if pre_missing_fields
        else "\nВсе основные поля присутствуют. Используй только факты из переданного JSON."
    )
    return (
        "Подготовь черновик карточки товара по следующим входным данным:\n"
        f"```json\n{json.dumps(payload, ensure_ascii=False, indent=2)}\n```\n"
        f"{missing_hint}\n\n"
        "КРИТИЧЕСКАЯ ПРОВЕРКА ПЕРЕД ОТВЕТОМ:\n"
        "- Длина `seo_title` должна быть <= 70 символов.\n"
        "- Длина `seo_description` должна быть строго в диапазоне 800..1200 символов (оптимально около 950–1050 символов).\n"
        "- Ни одной выдуманной цифры в `seo_description` и `structured_specs`, которой нет во входном JSON!"
    )


def build_length_correction_prompt(
    product: ProductInput,
    current_description: str,
    unverified_nums: list[str],
) -> str:
    """Промпт для точечной коррекции длины seo_description (800–1200 символов) и удаления непроверенных чисел."""
    curr_len = len(current_description)
    if curr_len < 800:
        direction = (
            f"Сейчас длина текста составляет {curr_len} символов (меньше минимума 800). "
            f"Расширь описание примерно на {950 - curr_len} символов (до диапазона 900–1100 символов), "
            "подробнее раскрыв сферы применения в промышленности, удобство эксплуатации, монтажа и контроля процесса, "
            "НЕ добавляя никаких новых цифр или вымышленных технических характеристик."
        )
    elif curr_len > 1200:
        direction = (
            f"Сейчас длина текста составляет {curr_len} символов (больше максимума 1200). "
            f"Сократи описание примерно на {curr_len - 1020} символов (до диапазона 900–1100 символов), "
            "убрав повторы и воду, но сохранив все реальные технические характеристики из входных данных."
        )
    else:
        direction = "Сохрани длину текста строго в пределах 850–1100 символов."

    num_warning = ""
    if unverified_nums:
        num_warning = (
            f"\nВНИМАНИЕ: в предыдущей версии текста обнаружены числа {unverified_nums}, которых НЕ БЫЛО во входных данных! "
            "Полностью удали эти числа из текста."
        )

    payload = {
        "name": product.name or "данных нет",
        "manufacturer": product.manufacturer or "данных нет",
        "specs": product.specs,
        "description": product.description or "данных нет",
    }
    return (
        f"Исправь поле `seo_description` для товара.\n{direction}{num_warning}\n\n"
        f"Исходные данные товара:\n```json\n{json.dumps(payload, ensure_ascii=False, indent=2)}\n```\n\n"
        f"Текущий черновик `seo_description` ({curr_len} симв.):\n{current_description}\n\n"
        'Верни СТРОГО JSON с одним полем: {"seo_description": "исправленный текст длиной 850-1100 символов"}'
    )
